import type { Category, ConditionGrade, Resource } from '@/types'
import { addDays, toDateInput } from '@/lib/format'

interface Spec {
  id: string
  ownerId: string
  name: string
  category: Category
  condition: ConditionGrade
  description: string
  conditionNotes?: string
  location: string
  distanceKm: number
  pricePerDay: number
  pricePerHour?: number
  deposit: number
  minCharge?: number
  accessories?: string[]
  conditions?: string[]
  /** Days from today the resource becomes free. 0 ⇒ available now. */
  freeIn?: number
  status?: Resource['availabilityStatus']
  rating: number
  ratingCount: number
  timesBorrowed: number
  tags: string[]
  approval?: Resource['approvalStatus']
  flagged?: boolean
  createdDaysAgo?: number
}

const DEFAULT_CONDITIONS = [
  'Return in the same condition',
  'No sub-lending to others',
  'Report any damage immediately',
]

function mk(s: Spec): Resource {
  return {
    id: s.id,
    ownerId: s.ownerId,
    name: s.name,
    category: s.category,
    description: s.description,
    condition: s.condition,
    conditionNotes: s.conditionNotes ?? 'Fully functional, no known issues.',
    images: [],
    location: s.location,
    distanceKm: s.distanceKm,
    pricePerDay: s.pricePerDay,
    pricePerHour: s.pricePerHour,
    minCharge: s.minCharge ?? Math.round(s.pricePerDay * 0.6),
    deposit: s.deposit,
    accessories: s.accessories ?? [],
    borrowingConditions: s.conditions ?? DEFAULT_CONDITIONS,
    availabilityStatus: s.status ?? (s.freeIn && s.freeIn > 0 ? 'borrowed' : 'available'),
    availableFrom: toDateInput(addDays(new Date(), s.freeIn ?? 0)),
    rating: s.rating,
    ratingCount: s.ratingCount,
    timesBorrowed: s.timesBorrowed,
    tags: s.tags,
    approvalStatus: s.approval ?? 'approved',
    flagged: s.flagged ?? false,
    createdAt: toDateInput(addDays(new Date(), -(s.createdDaysAgo ?? 60))),
  }
}

